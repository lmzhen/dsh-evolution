/**
 * The panel body: a four-state summary plus the list aggregated BY RULE.
 *
 * It renders plain data and callbacks handed in by the sidebar (`inject`), never a service, and it
 * holds no facts of its own. Two rules of the house are visible here: a rule whose threshold is not
 * calibrated yet is NAMED WITHOUT A NUMBER (the number is the thing we do not have), and a skill
 * that could not be read is listed as unreadable — silence would read as a pass.
 * @module @deepseek-ai/dsh-evolution-skill-health/client
 */

import { createElement, useEffect, useState, type ReactNode } from 'react'
// The stylesheet is scoped to this class; without it on the root element the panel renders unstyled.
import { CSS_TAG_ID } from './styles.ts'
import type { HealthOutcome } from './api.ts'
import { platformSegmentedTabs } from './platform-tabs.ts'
import type { RouteFailure } from '@lmzhen/dsh-evolution-client-kit/generated/route-client'
import { FailureBlock } from '@lmzhen/dsh-evolution-client-kit/generated/states'
import { FALLBACKS } from '@lmzhen/dsh-evolution-client-kit/generated/fallbacks'

/** One finding, as the host reports it: `line` is null when the position cannot be named. */
export interface HealthFinding {
  rule: string
  count: number
  line: string | null
  /** False for a rule whose threshold is not calibrated: the rule is named, the count is not shown. */
  countIsMeaningful: boolean
  severity?: 'warn' | 'error'
  message?: string
}

/** Measured dimensions behind a row; absent when the scan could not read them. */
export interface HealthDims {
  bodyChars: number | null
  bodyTokens: number | null
  supportGroups: number
  supportFiles: number | null
  churnPatches: number | null
  churnReads: number | null
  stampDensityPerKb: number | null
}

/** One skill row. `readable: false` is its own verdict — never folded into `ok`. */
export interface HealthRow {
  name: string
  verdict: 'healthy' | 'warn' | 'error' | 'unreadable' | 'needs-restructure'
  findings: HealthFinding[]
  dims?: HealthDims | null
  /** Non-null when a protection marker owns the skill. */
  protection?: string | null
  /** Mechanical hard-cap hits; null = event log unreadable, never 0-as-unknown. */
  hardCapHits?: number | null
}

/** One semantic proposal as the health lane projects it; never generated by this panel. */
export interface HealthProposal {
  id: string
  source: string
  outcome: 'keep' | 'extract' | 'mixed' | 'owner-gap'
  owner: { mode: 'covered' | 'owner-gap'; name?: string; neededOwner?: string }
  status: 'proposed' | 'previewed' | 'stale' | 'dismissed'
  parts?: Array<{ heading: string }>
  residual?: string
  warnings?: string[]
  provenance?: { promptVersion: string; promptHash?: string; model?: string; runId: string; at: number }
}

/** What the sidebar hands the component. */
export interface HealthFace {
  rows: HealthRow[]
  /** Semantic proposals from the one proposer; empty means none were handed in. */
  proposals?: HealthProposal[]
  /** True when the host could not finish the scan: the counts below are then a lower bound. */
  truncated: boolean
  /** Opens the skill-history panel for one skill, when that panel is present. */
  openHistory?: (name: string) => void
  /** Reads the scan result from the host route. Absent faces render their seeded rows unchanged. */
  loadRows?: () => Promise<HealthOutcome>
  /** Whether the host has answered at least once; the seed is not an empty result. */
  loaded?: boolean
  /** Semantic proposals are a separate lane; unavailable must not read as "nothing to extract". */
  proposalStatus?: 'available' | 'unavailable' | 'stale'
  /** Host scan time and status, when the route supplied them. */
  readAt?: number
  scan?: { status: 'complete' | 'unavailable' | 'truncated' }
  /** The seat's translator for this bundle's dictionary — the panel never reaches for a service. */
  t: (key: string) => string
}

/** Kinds in the order the summary reads them. */
const KINDS = ['healthy', 'warn', 'needs-restructure', 'error', 'unreadable'] as const

/** UI tone per verdict; the CSS keys are ok/warn/error/unreadable. */
const RULE_KEYS = new Set(['unreadable-skill', 'body-oversize-2x', 'body-oversize', 'stamp-density', 'body-without-support', 'references-sprawl', 'scope-overloaded', 'write-ghost'])

/** A rule speaks the operator's language; an unknown rule keeps its raw id rather than inventing one. */
function ruleName(t: (key: string) => string, rule: string): string {
  if (!RULE_KEYS.has(rule)) return rule
  const key = 'rule.' + rule
  const label = t(key)
  return label === key ? rule : label
}

const TONE: Readonly<Record<HealthRow['verdict'], string>> = Object.freeze({
  healthy: 'ok',
  warn: 'warn',
  'needs-restructure': 'warn',
  error: 'error',
  unreadable: 'unreadable',
})

/** One row per rule, with the skills that carry it — the view the report is actually read in. */
function byRule(rows: readonly HealthRow[]): Array<{ rule: string; count: number; skills: string[] }> {
  const table = new Map<string, { rule: string; count: number; skills: string[] }>()
  for (const row of rows) {
    for (const finding of row.findings) {
      const entry = table.get(finding.rule) ?? { rule: finding.rule, count: 0, skills: [] }
      entry.count = finding.countIsMeaningful ? entry.count + finding.count : entry.count
      entry.skills.push(row.name)
      table.set(finding.rule, entry)
    }
  }
  return [...table.values()].sort((a, b) => b.skills.length - a.skills.length || a.rule.localeCompare(b.rule))
}

/** The verdict a rule's row speaks in: the worst one among the skills that carry it. */
function worstVerdict(face: HealthFace, skills: readonly string[]): string {
  const order = ['error', 'needs-restructure', 'warn', 'unreadable', 'healthy']
  let worst = 'healthy'
  for (const row of face.rows) {
    if (!skills.includes(row.name)) continue
    if (order.indexOf(row.verdict) < order.indexOf(worst)) worst = row.verdict
  }
  return worst
}

/** A copy button that reports the clipboard verdict instead of swallowing it. */
function CopyButton(props: { command: string; t: (key: string) => string; role: string; label: string }): ReactNode {
  const [state, setState] = useState<'idle' | 'ok' | 'fail'>('idle')
  const copy = async (): Promise<void> => {
    try {
      if (typeof navigator === 'undefined' || navigator.clipboard === undefined) throw new Error('clipboard unavailable')
      await navigator.clipboard.writeText(props.command)
      setState('ok')
    } catch { setState('fail') }
  }
  const text = state === 'ok' ? props.t('copy.copied') : state === 'fail' ? props.t('copy.failed') : props.label
  return createElement('button', { type: 'button', 'data-role': props.role, 'data-copy-state': state, onClick: () => { void copy() } }, text)
}

/** H4: the evidence queue by skill, before the by-rule summary. */
function skillQueue(face: HealthFace, t: (key: string) => string): ReactNode {
  const order = ['error', 'needs-restructure', 'warn', 'unreadable', 'healthy']
  const rows = [...face.rows].sort((a, b) => order.indexOf(a.verdict) - order.indexOf(b.verdict) || a.name.localeCompare(b.name))
  return createElement('div', { 'data-role': 'skill-queue' },
    createElement('h3', { 'data-role': 'group-title' }, t('group.bySkill')),
    ...rows.map(row => createElement('div', { key: row.name, 'data-role': 'skill-row', 'data-tone': row.verdict },
      createElement('span', { 'data-role': 'skill-name' }, row.name),
      createElement('span', { 'data-role': 'skill-verdict' }, t('verdict.' + row.verdict)),
      createElement('span', { 'data-role': 'skill-findings' }, row.findings.length === 0 ? t('findings.none') : row.findings.map(finding => ruleName(t, finding.rule)).join(' / ')),
      row.verdict === 'unreadable' ? createElement('span', { 'data-role': 'skill-unreadable-note' }, t('unreadable.note')) : null,
      row.protection === undefined || row.protection === null ? null : createElement('span', { 'data-role': 'skill-protection' }, t('protected') + ': ' + row.protection),
      createElement('span', { 'data-role': 'skill-dims' }, t('dims.body') + ': ' + String(row.dims?.bodyChars ?? t('dims.unknown')) + ' · ' + t('dims.support') + ': ' + String(row.dims?.supportFiles ?? t('dims.unknown'))),
      createElement('span', { 'data-role': 'skill-row-actions' },
        createElement('button', { type: 'button', 'data-role': 'action-history', disabled: face.openHistory === undefined, onClick: () => { face.openHistory?.(row.name) } }, t('action.history')),
        createElement(CopyButton, { command: '/evolution skill history ' + row.name, t, role: 'action-copy', label: t('action.copy') }),
      ),
    )),
  )
}

/** The rule table: a grid so counts line up, with a tone bar per row and skill pills. */
function ruleTable(face: HealthFace, t: (key: string) => string): ReactNode {
  const rows = byRule(face.rows)
  const cell = (role: string, children: ReactNode, key?: string): ReactNode =>
    createElement('td', key === undefined ? { 'data-role': role } : { 'data-role': role, key }, children)
  return createElement('table', { 'data-role': 'rule-table' },
    createElement('thead', null, createElement('tr', { 'data-role': 'rule-head' },
      createElement('th', { scope: 'col', 'data-role': 'rule-name' }, t('col.rule')),
      createElement('th', { scope: 'col', 'data-role': 'skills' }, t('col.skills')),
      createElement('th', { scope: 'col', 'data-role': 'rule-count' }, t('col.count')),
    )),
    createElement('tbody', null, rows.map(entry => createElement('tr', {
      key: entry.rule,
      'data-role': 'rule-row',
      'data-tone': TONE[worstVerdict(face, entry.skills) as HealthRow['verdict']],
    },
    cell('rule-name', ruleName(t, entry.rule)),
    cell('skills', entry.skills.map((name, i) => createElement('span', { 'data-role': 'skill-pill', key: name + ':' + String(i), title: name }, name))),
    cell('rule-count', entry.count === 0 ? t('count.notCalibrated') : String(entry.count)),
    ))),
  )
}

/**
 * Render the panel.
 * @param props - the face (`{ rows, truncated, openHistory? }`) and the locale seat's translator.
 * @returns the panel body.
 */
/** Fill the generated block's `{slot}` copies with this bundle's dictionary. */
function fillCopy(template: string, values: Readonly<Record<string, string | number>>): string {
  return template.replace(/\{(\w+)\}/g, (match, slot: string) => {
    const value = values[slot]
    return value === undefined ? match : String(value)
  })
}

/** The shared four-state failure block, spoken through this bundle's keys. */
function failureBlock(t: (key: string) => string, failure: RouteFailure): ReactNode {
  const translate = (key: string, values?: Readonly<Record<string, string | number>>): string => {
    const text = t(key)
    return values === undefined ? text : fillCopy(text, values)
  }
  return FailureBlock({ failure, t: translate, fallback: FALLBACKS['skill-health'] })
}

export function SkillHealthPanel(face: HealthFace): ReactNode {
  const t = face.t
  // The face seeds the first paint; the host route replaces it once read. A refusal keeps the seed
  // (so the counts stay a lower bound) and reports the host's own sentence instead of a verdict.
  const [view, setView] = useState<HealthFace>(face)
  const [failed, setFailed] = useState<RouteFailure | undefined>(undefined)
  const [loading, setLoading] = useState(face.loadRows !== undefined && face.loaded !== true)
  const [lastReadAt, setLastReadAt] = useState<number | undefined>(face.readAt)
  const [scan, setScan] = useState(face.scan)
  const [viewMode, setViewMode] = useState<'skills' | 'rules'>('skills')
  /** One read trigger for first paint and the refresh button; the latest answer wins. */
  const load = (): (() => void) => {
    const read = face.loadRows
    if (read === undefined) return () => {}
    let live = true
    setLoading(true)
    read()
      .then((outcome) => {
        if (!live) return
        if (outcome.ok) {
          const payload = outcome.payload
          setView({
            ...face,
            rows: payload.rows,
            truncated: payload.truncated,
            proposals: payload.proposals ?? [],
            loaded: true,
            ...(payload.proposalStatus === undefined ? {} : { proposalStatus: payload.proposalStatus }),
          })
          setLastReadAt(payload.readAt)
          setScan(payload.scan)
          setFailed(undefined)
        } else setFailed(outcome.failure)
      })
      .catch(() => { if (live) setFailed({ kind: 'server', status: 0 }) })
      .finally(() => { if (live) setLoading(false) })
    return () => { live = false }
  }
  useEffect(() => load(), [face])
  const counts = new Map(KINDS.map(kind => [kind, view.rows.filter((row: HealthRow) => row.verdict === kind).length]))
  // Four verdict cards, not one sentence: the number is the fact a reader scans for, and the tone
  // bar carries the severity. A verdict with no rows still shows its zero — silence would read as
  // 'not checked' rather than 'nothing found'.
  const stats = createElement('div', { 'data-role': 'stats' },
    KINDS.map(kind => createElement('div', { key: kind, 'data-role': 'stat', 'data-tone': TONE[kind] },
      createElement('div', { 'data-role': 'stat-value' }, String(counts.get(kind) ?? 0)),
      createElement('div', { 'data-role': 'stat-label' }, t('verdict.' + kind)),
    )),
  )
  return createElement('section', { className: CSS_TAG_ID },
    createElement('div', { 'data-role': 'header' },
      createElement('span', { 'data-role': 'read-at' }, lastReadAt === undefined ? t('readAt.unknown') : new Date(lastReadAt).toLocaleString()),
      createElement('span', { 'data-role': 'scan-status' }, t('scan.' + (scan?.status ?? 'unavailable'))),
      createElement('button', { type: 'button', 'data-role': 'refresh', disabled: loading, onClick: () => { load() } }, t('refresh')),
    ),
    createElement('p', { 'data-role': 'hint' }, t('hint')),
    loading || failed !== undefined || scan?.status === 'unavailable' ? null : stats,
    loading ? createElement('p', { 'data-role': 'note' }, t('loading')) : null,
    view.truncated ? createElement('p', { 'data-role': 'note' }, t('scan.truncated')) : null,
    failed === undefined ? null : createElement('div', { 'data-role': 'note' }, failureBlock(t, failed)),
    view.loaded === true && view.rows.length === 0 ? createElement('p', { 'data-role': 'note' }, t('empty.noneReported')) : null,
    view.proposalStatus === 'unavailable' && (view.proposals ?? []).length === 0
      ? createElement('p', { 'data-role': 'note' }, t('proposal.unavailable'))
      : null,
    view.proposalStatus === 'stale' && (view.proposals ?? []).length === 0
      ? createElement('p', { 'data-role': 'note' }, t('proposal.stale'))
      : null,
    (view.proposals ?? []).length > 0
      ? createElement('div', { 'data-role': 'proposals' },
        createElement('h3', { 'data-role': 'group-title' }, t('group.proposals')),
        ...(view.proposals ?? []).map(proposal => {
          const heading = proposal.parts?.[0]?.heading
          const target = proposal.owner.mode === 'covered' ? proposal.owner.name : proposal.owner.neededOwner
          const command = heading === undefined || target === undefined
            ? undefined
            : '/evolution extract ' + proposal.source + ' ' + target + ' "' + heading + '" --plan'
          return createElement('div', { key: proposal.id, 'data-role': 'proposal' },
            createElement('p', { 'data-role': 'proposal-summary' }, proposal.source + ' — ' + t('proposal.outcome.' + proposal.outcome)),
            createElement('p', { 'data-role': 'proposal-status' }, t('proposal.status.' + proposal.status)),
            createElement('details', { 'data-role': 'proposal-provenance' },
              createElement('summary', null, t('proposal.provenance')),
              createElement('p', { 'data-role': 'proposal-owner' }, t('proposal.owner') + ': ' +
                (proposal.owner.mode === 'covered'
                  ? t('proposal.owner.covered') + (proposal.owner.name === undefined ? '' : ': ' + proposal.owner.name)
                  : t('proposal.owner.owner-gap') + (proposal.owner.neededOwner === undefined ? '' : ': ' + proposal.owner.neededOwner))),
              proposal.provenance === undefined ? null : createElement('p', null, proposal.provenance.promptVersion + (proposal.provenance.model === undefined ? '' : ' · ' + proposal.provenance.model) + ' · ' + proposal.provenance.runId + ' · ' + new Date(proposal.provenance.at).toLocaleString() + (proposal.provenance.promptHash === undefined ? '' : ' · #' + proposal.provenance.promptHash.slice(0, 8)))),
            proposal.residual === undefined || proposal.residual.trim() === '' ? null : createElement('p', { 'data-role': 'proposal-kept' },
              t('proposal.kept') + ': ' + proposal.residual.trim().slice(0, 160)),
            (proposal.parts ?? []).length === 0 ? null : createElement('p', { 'data-role': 'proposal-reusable' },
              t('proposal.reusable') + ': ' + (proposal.parts ?? []).map(part => part.heading).join('、')),
            (proposal.warnings ?? []).length === 0 ? null : createElement('p', { 'data-role': 'proposal-warnings' },
              t('proposal.warnings') + ': ' + (proposal.warnings ?? []).join('；')),
            command === undefined ? null : createElement('p', { 'data-role': 'proposal-command' },
              createElement('code', {}, command),
              createElement(CopyButton, { command, t, role: 'proposal-copy', label: t('proposal.copy') }),
            ),
          )
        }),
      )
      : null,
    (() => {
      const Tabs = platformSegmentedTabs()
      const items = [
        { value: 'skills', label: t('group.bySkill'), id: 'evo-health-tab-skills', panelId: 'evo-health-skills' },
        { value: 'rules', label: t('group.byRule'), id: 'evo-health-tab-rules', panelId: 'evo-health-rules' },
      ] as const
      if (Tabs !== undefined) {
        return createElement(Tabs as never, { items, value: viewMode, onChange: (next: string) => { setViewMode(next === 'rules' ? 'rules' : 'skills') }, label: t('group.byRule') })
      }
      return createElement('div', { role: 'tablist', 'data-role': 'view-tabs' },
        items.map(item => createElement('button', {
          key: item.value, type: 'button', role: 'tab', 'aria-selected': viewMode === item.value ? 'true' : 'false',
          'aria-controls': item.panelId, id: item.id,
          onClick: () => { setViewMode(item.value === 'rules' ? 'rules' : 'skills') },
        }, item.label)))
    })(),
    viewMode === 'skills'
      ? createElement('div', { id: 'evo-health-skills', role: 'tabpanel' }, skillQueue(view, t))
      : createElement('div', { id: 'evo-health-rules', role: 'tabpanel' },
        createElement('h3', { 'data-role': 'group-title' }, t('group.byRule')), ruleTable(view, t)),
  )
}
