#!/usr/bin/env node
/** Generate the host human error table from the single catalog. */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..', '..')
const SOURCE = resolve(ROOT, 'packages/scripts/i18n/catalog/host.errors.json')
const TARGET = resolve(ROOT, 'packages/evolution-commands/src/generated/host-errors.ts')
const LOCALES = ['zh', 'en', 'ja', 'es', 'fr', 'de', 'ru', 'pt']
const CHECK = process.argv.includes('--check')
const STRICT = process.argv.includes('--strict')

const source = JSON.parse(await readFile(SOURCE, 'utf8'))
const messages = source.messages
if (typeof messages !== 'object' || messages === null) throw new Error('messages required')
const rows = {}
const missing = []
for (const [id, row] of Object.entries(messages)) {
  if (typeof row.en !== 'string' || row.en.length === 0) throw new Error(id + ': en required')
  const out = {}
  for (const locale of LOCALES) {
    if (typeof row[locale] === 'string' && row[locale].length > 0) out[locale] = row[locale]
    else { out[locale] = row.en; missing.push(id + ':' + locale) }
  }
  rows[id] = out
}
if (STRICT && missing.length > 0) throw new Error('missing translations: ' + missing.slice(0, 8).join(', '))
const output = [
  '/**',
  ' * GENERATED by packages/scripts/gen-host-errors.mjs — do not edit.',
  ' * Source: packages/scripts/i18n/catalog/host.errors.json.',
  ' */',
  '',
  'export const HOST_LOCALES = ' + JSON.stringify(LOCALES) + ' as const',
  'export type HostLocale = typeof HOST_LOCALES[number]',
  '',
  'export const HOST_ERRORS = ' + JSON.stringify(rows, null, 2).replace(/\n/g, '\n  ') + ' as const',
  '',
  'export type HostErrorId = keyof typeof HOST_ERRORS',
  '',
].join('\n') + '\n'
const current = await readFile(TARGET, 'utf8').catch(() => '')
if (CHECK) {
  if (current !== output) { console.error('gen-host-errors: generated table is stale'); process.exit(1) }
  console.log('gen-host-errors: OK — ' + String(Object.keys(rows).length) + ' error(s)')
} else {
  await mkdir(dirname(TARGET), { recursive: true })
  await writeFile(TARGET, output)
  console.log('gen-host-errors: wrote ' + TARGET)
}
