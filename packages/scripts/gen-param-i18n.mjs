#!/usr/bin/env node
/** Generate localized parameter labels/hints/units/enum names from the catalog. */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..', '..')
const SOURCE = resolve(ROOT, 'packages/scripts/i18n/catalog/param-copy.json')
const TARGET = resolve(ROOT, 'packages/evolution-ui/src/panels/settings/generated-param-i18n.ts')
const LOCALES = ['zh', 'en', 'ja', 'es', 'fr', 'de', 'ru', 'pt']
const CHECK = process.argv.includes('--check')
const STRICT = process.argv.includes('--strict')

function fill(row, where) {
  if (typeof row !== 'object' || row === null) throw new Error(where + ': row must be an object')
  if (typeof row.en !== 'string' || row.en.length === 0) throw new Error(where + ': en required')
  const out = {}
  const missing = []
  for (const locale of LOCALES) {
    if (typeof row[locale] === 'string' && row[locale].length > 0) out[locale] = row[locale]
    else { out[locale] = row.en; missing.push(where + ':' + locale) }
  }
  if (STRICT && missing.length > 0) throw new Error('missing translations: ' + missing.slice(0, 8).join(', '))
  return out
}

const source = JSON.parse(await readFile(SOURCE, 'utf8'))
const groups = Object.fromEntries(Object.entries(source.groups).map(([id, row]) => [id, fill(row, 'group.' + id)]))
const units = Object.fromEntries(Object.entries(source.units).map(([id, row]) => [id, fill(row, 'unit.' + id)]))
const fields = Object.fromEntries(Object.entries(source.fields).map(([id, row]) => [id, {
  label: fill(row.label, 'field.' + id + '.label'),
  hint: fill(row.hint, 'field.' + id + '.hint'),
}]))
const values = Object.fromEntries(Object.entries(source.values).map(([id, rows]) => [id,
  Object.fromEntries(Object.entries(rows).map(([value, row]) => [value, fill(row, 'field.' + id + '.value.' + value)])),
]))

const render = (value) => JSON.stringify(value, null, 2).replace(/\n/g, '\n  ')
const lines = [
  '/**',
  ' * GENERATED by packages/scripts/gen-param-i18n.mjs — do not edit.',
  ' * Source: packages/scripts/i18n/catalog/param-copy.json.',
  ' */',
  '',
  'export const PARAM_GROUPS = ' + render(groups) + ' as const',
  '',
  'export const PARAM_UNITS = ' + render(units) + ' as const',
  '',
  'export const PARAM_FIELDS = ' + render(fields) + ' as const',
  '',
  'export const PARAM_VALUES = ' + render(values) + ' as const',
  '',
]
const output = lines.join('\n') + '\n'
const current = await readFile(TARGET, 'utf8').catch(() => '')
if (CHECK) {
  if (current !== output) { console.error('gen-param-i18n: generated copy is stale'); process.exit(1) }
  console.log('gen-param-i18n: OK — ' + String(Object.keys(fields).length) + ' field(s)')
} else {
  await writeFile(TARGET, output)
  console.log('gen-param-i18n: wrote ' + TARGET)
}
