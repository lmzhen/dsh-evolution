#!/usr/bin/env node
/**
 * G5/W6-W7 client seam generator: renders the client route table and the shared route client into the
 * three UI packages, from the ONE host declaration (evolution-core HOST_ROUTES).
 *
 * R13 (W6): the publish pipeline builds first, so the generator prefers the BUILT core lib. A mirror
 * checkout has no lib; there it falls back to a constrained static read of src/http-routes.ts (the
 * HOST_ROUTES literal only). Both paths emit identical bytes, and --check makes drift red either way.
 *
 * The rendered artifacts are checked in: a browser half cannot import @deepseek-ai/* at runtime, so the
 * copies are the shipping form of the table; the generator's --check and verify-host-routes keep them
 * stale-proof.
 *
 * Usage: node packages/scripts/gen-client-seam.mjs <root> [--check] [--json]
 *   root: 'packages' (mirror) or 'packages/evolution' (overlay)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const argv = process.argv.slice(2)
const rootArg = argv.find((arg) => !arg.startsWith('--')) ?? 'packages'
const root = resolve(rootArg)
const CHECK = argv.includes('--check')
const JSON_OUT = argv.includes('--json')
const HERE = resolve(new URL('.', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const scriptsDir = existsSync(join(root, 'scripts')) ? join(root, 'scripts') : HERE
const templates = join(scriptsDir, 'templates', 'client')
const PACKAGES = ['evolution-settings-ui', 'evolution-skill-history', 'evolution-skill-health']

const SURFACE_IDS = {
  approval: 'approval',
  skillHistory: 'skill-history',
  skillHealth: 'skill-health',
  diagnostics: 'diagnostics',
}

/** Read HOST_ROUTES: built lib first (R13), constrained source fallback for mirror checkouts. */
async function loadHostRoutes() {
  const lib = join(root, 'evolution-core', 'lib', 'http-routes.js')
  if (existsSync(lib)) {
    const module = await import(pathToFileURL(lib).href)
    if (module.HOST_ROUTES !== undefined) return module.HOST_ROUTES
  }
  const sourcePath = join(root, 'evolution-core', 'src', 'http-routes.ts')
  if (!existsSync(sourcePath)) {
    console.error('gen-client-seam: cannot find HOST_ROUTES (no built lib and no ' + sourcePath + ')')
    process.exit(2)
  }
  const source = readFileSync(sourcePath, 'utf8')
  const match = /export const HOST_ROUTES = (\{[\s\S]*?\n\}) as const/.exec(source)
  if (match === null) {
    console.error('gen-client-seam: could not find the HOST_ROUTES literal in ' + sourcePath)
    process.exit(2)
  }
  // Trusted repository source, literal object only: evaluate it as data (no identifiers expected).
  return new Function('return (' + match[1] + ')')()
}

function renderRoutes(hostRoutes) {
  const surfaces = Object.keys(SURFACE_IDS).filter((key) => hostRoutes[key] !== undefined)
  if (surfaces.length === 0) {
    console.error('gen-client-seam: HOST_ROUTES is empty')
    process.exit(2)
  }
  const union = surfaces.map((key) => "'" + SURFACE_IDS[key] + "'").join(' | ')
  const body = {}
  for (const key of surfaces) body[SURFACE_IDS[key]] = hostRoutes[key]
  const header = '// GENERATED by packages/scripts/gen-client-seam.mjs from evolution-core HOST_ROUTES — do not edit.'
  const template = readFileSync(join(templates, 'routes.ts.tmpl'), 'utf8')
  return template
    .replace('{{HEADER}}', header)
    .replace('{{SURFACE_UNION}}', union)
    .replace('{{ROUTES_BODY}}', JSON.stringify(body, null, 2))
}

function renderRouteClient() {
  const header = '// GENERATED by packages/scripts/gen-client-seam.mjs from packages/scripts/templates/client/route-client.ts.tmpl — do not edit.'
  return readFileSync(join(templates, 'route-client.ts.tmpl'), 'utf8').replace('{{HEADER}}', header)
}

const hostRoutes = await loadHostRoutes()
const outputs = []
const routesText = renderRoutes(hostRoutes)
const clientText = renderRouteClient()
for (const pkg of PACKAGES) {
  const dir = join(root, pkg, 'src', 'client')
  if (!existsSync(dir)) {
    console.error('gen-client-seam: client directory is missing: ' + dir)
    process.exit(2)
  }
  outputs.push({ path: join(dir, 'routes.generated.ts'), content: routesText })
  outputs.push({ path: join(dir, 'route-client.generated.ts'), content: clientText })
}

const drifts = []
for (const output of outputs) {
  const current = existsSync(output.path) ? readFileSync(output.path, 'utf8') : undefined
  if (current === output.content) continue
  drifts.push(output.path)
  if (!CHECK) writeFileSync(output.path, output.content, 'utf8')
}
if (CHECK && drifts.length > 0) {
  if (JSON_OUT) console.log(JSON.stringify({ ok: false, drifted: drifts }, null, 2))
  else {
    console.error('gen-client-seam --check: ' + drifts.length + ' generated client file(s) are stale:')
    for (const drift of drifts) console.error('  - ' + drift)
  }
  process.exit(1)
}
if (JSON_OUT) console.log(JSON.stringify({ ok: true, check: CHECK, wrote: CHECK ? [] : drifts, endpoints: Object.values(hostRoutes).reduce((sum, surface) => sum + Object.keys(surface).length, 0) }, null, 2))
else console.log('gen-client-seam: ' + (CHECK ? 'OK — ' + String(outputs.length) + ' generated client file(s) in sync' : 'wrote ' + String(drifts.length) + ' generated client file(s)'))
