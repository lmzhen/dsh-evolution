#!/usr/bin/env node
/**
 * G5/W6-W7 client seam generator: renders the client route table and the shared route client into the
 * three UI packages, from the ONE host declaration (evolution-core HOST_ROUTES).
 *
 * R13 (W6): the publish pipeline builds first, so the generator prefers the BUILT core lib. A mirror
 * checkout has no lib; there it falls back to a constrained static read of src/http-routes.ts (the
 * HOST_ROUTES literal only). Both paths emit identical bytes, and --check makes drift red either way.
 *
 * The rendered artifacts are checked in: a browser half cannot import @deepseek-ai/* at runtime, so the
 * copies are the shipping form of the table; the generator's --check and verify-host-routes keep them
 * stale-proof.
 *
 * Usage: node packages/scripts/gen-client-seam.mjs <root> [--check] [--json]
 *   root: 'packages' (mirror) or 'packages/evolution' (overlay)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const argv = process.argv.slice(2)
const rootArg = argv.find((arg) => !arg.startsWith('--')) ?? 'packages'
const root = resolve(rootArg)
const CHECK = argv.includes('--check')
const JSON_OUT = argv.includes('--json')
import { tsLiteral } from './lib-ts-literal.mjs'

const HERE = resolve(new URL('.', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const scriptsDir = existsSync(join(root, 'scripts')) ? join(root, 'scripts') : HERE
const templates = join(scriptsDir, 'templates', 'client')
const PACKAGES = ['evolution-settings-ui', 'evolution-skill-history', 'evolution-skill-health']

const SURFACE_IDS = {
  approval: 'approval',
  skillHistory: 'skill-history',
  skillHealth: 'skill-health',
  merge: 'merge',
  diagnostics: 'diagnostics',
}

/** Read HOST_ROUTES: built lib first (R13), constrained source fallback for mirror checkouts. */
async function loadHostRoutes() {
  const lib = join(root, 'evolution-core', 'lib', 'http-routes.js')
  if (existsSync(lib)) {
    const module = await import(pathToFileURL(lib).href)
    if (module.HOST_ROUTES !== undefined) return module.HOST_ROUTES
  }
  const sourcePath = join(root, 'evolution-core', 'src', 'http-routes.ts')
  if (!existsSync(sourcePath)) {
    console.error('gen-client-seam: cannot find HOST_ROUTES (no built lib and no ' + sourcePath + ')')
    process.exit(2)
  }
  const source = readFileSync(sourcePath, 'utf8')
  const match = /export const HOST_ROUTES = (\{[\s\S]*?\n\}) as const/.exec(source)
  if (match === null) {
    console.error('gen-client-seam: could not find the HOST_ROUTES literal in ' + sourcePath)
    process.exit(2)
  }
  // Trusted repository source, literal object only: evaluate it as data (no identifiers expected).
  return new Function('return (' + match[1] + ')')()
}

function renderRoutes(hostRoutes) {
  const surfaces = Object.keys(SURFACE_IDS).filter((key) => hostRoutes[key] !== undefined)
  if (surfaces.length === 0) {
    console.error('gen-client-seam: HOST_ROUTES is empty')
    process.exit(2)
  }
  const union = surfaces.map((key) => "'" + SURFACE_IDS[key] + "'").join(' | ')
  const body = {}
  for (const key of surfaces) body[SURFACE_IDS[key]] = hostRoutes[key]
  const header = '// GENERATED by packages/scripts/gen-client-seam.mjs from evolution-core HOST_ROUTES — do not edit.'
  const template = readFileSync(join(templates, 'routes.ts.tmpl'), 'utf8')
  return template
    .replace('{{HEADER}}', header)
    .replace('{{SURFACE_UNION}}', union)
    .replace('{{ROUTES_BODY}}', tsLiteral(body))
}

/** Read COMMAND_FALLBACKS: built commands lib first, constrained source fallback. */
async function loadCommandFallbacks() {
  const lib = join(root, 'evolution-commands', 'lib', 'command-fallback.js')
  if (existsSync(lib)) {
    const module = await import(pathToFileURL(lib).href)
    if (module.COMMAND_FALLBACKS !== undefined) return { table: module.COMMAND_FALLBACKS, order: module.COMMAND_FALLBACK_SURFACES }
  }
  const sourcePath = join(root, 'evolution-commands', 'src', 'command-fallback.ts')
  if (!existsSync(sourcePath)) {
    console.error('gen-client-seam: cannot find COMMAND_FALLBACKS (no built lib and no ' + sourcePath + ')')
    process.exit(2)
  }
  const source = readFileSync(sourcePath, 'utf8')
  const tableStart = source.indexOf('export const COMMAND_FALLBACKS')
  const open = tableStart < 0 ? -1 : source.indexOf('{', source.indexOf('=', tableStart))
  if (open < 0) {
    console.error('gen-client-seam: could not find the COMMAND_FALLBACKS literal in ' + sourcePath)
    process.exit(2)
  }
  let depth = 0
  let close = -1
  for (let index = open; index < source.length; index += 1) {
    const ch = source[index]
    if (ch === '{') depth += 1
    else if (ch === '}') {
      depth -= 1
      if (depth === 0) { close = index; break }
    }
  }
  if (close < 0) {
    console.error('gen-client-seam: COMMAND_FALLBACKS literal is not balanced in ' + sourcePath)
    process.exit(2)
  }
  const table = new Function('return (' + source.slice(open, close + 1) + ')')()
  const orderStart = source.indexOf('export const COMMAND_FALLBACK_SURFACES')
  const orderOpen = orderStart < 0 ? -1 : source.indexOf('[', orderStart)
  const orderClose = orderOpen < 0 ? -1 : source.indexOf(']', orderOpen)
  const order = orderOpen < 0 || orderClose < 0 ? undefined : new Function('return (' + source.slice(orderOpen, orderClose + 1) + ')')()
  return { table, order }
}

/** Read the frozen diagnostics key arrays from core source (or built lib). */
async function loadDiagnosticKeys() {
  const lib = join(root, 'evolution-core', 'lib', 'diagnostics.js')
  if (existsSync(lib)) {
    const module = await import(pathToFileURL(lib).href)
    if (Array.isArray(module.DIAGNOSTICS_FACT_KEYS) && Array.isArray(module.DIAGNOSTICS_RUNTIME_KEYS)) {
      return { facts: module.DIAGNOSTICS_FACT_KEYS, runtime: module.DIAGNOSTICS_RUNTIME_KEYS }
    }
  }
  const sourcePath = join(root, 'evolution-core', 'src', 'diagnostics.ts')
  if (!existsSync(sourcePath)) {
    console.error('gen-client-seam: cannot find diagnostics keys (no built lib and no ' + sourcePath + ')')
    process.exit(2)
  }
  const source = readFileSync(sourcePath, 'utf8')
  const readArray = (name) => {
    const start = source.indexOf('export const ' + name)
    const open = start < 0 ? -1 : source.indexOf('[', start)
    const close = open < 0 ? -1 : source.indexOf(']', open)
    if (close < 0) {
      console.error('gen-client-seam: could not read ' + name + ' from ' + sourcePath)
      process.exit(2)
    }
    const body = source.slice(open + 1, close)
    const items = body.split(',').map((part) => part.trim()).filter((part) => part !== '').map((part) => part.replaceAll("'", ''))
    return items
  }
  return { facts: readArray('DIAGNOSTICS_FACT_KEYS'), runtime: readArray('DIAGNOSTICS_RUNTIME_KEYS') }
}

function renderStates() {
  const header = '// GENERATED by packages/scripts/gen-client-seam.mjs from packages/scripts/templates/client/states.ts.tmpl — do not edit.'
  return readFileSync(join(templates, 'states.ts.tmpl'), 'utf8').replace('{{HEADER}}', header)
}

function renderContracts(keys) {
  const header = '// GENERATED by packages/scripts/gen-client-seam.mjs from evolution-core diagnostics.ts + templates/client/contracts.ts.tmpl — do not edit.'
  const union = (items) => items.map((item) => "'" + item + "'").join(' | ')
  return readFileSync(join(templates, 'contracts.ts.tmpl'), 'utf8')
    .replace('{{HEADER}}', header)
    .replace('{{FACT_KEY_UNION}}', union(keys.facts))
    .replace('{{RUNTIME_KEY_UNION}}', union(keys.runtime))
}

function renderContractsLegacy() {
  const header = '// GENERATED by packages/scripts/gen-client-seam.mjs from packages/scripts/templates/client/contracts.ts.tmpl — do not edit.'
  return readFileSync(join(templates, 'contracts.ts.tmpl'), 'utf8').replace('{{HEADER}}', header)
}

function renderFallbacks(surfaceUnion, fallbacks) {
  const header = '// GENERATED by packages/scripts/gen-client-seam.mjs from evolution-commands COMMAND_FALLBACKS — do not edit.'
  return readFileSync(join(templates, 'fallbacks.ts.tmpl'), 'utf8')
    .replace('{{HEADER}}', header)
    .replace('{{SURFACE_UNION}}', surfaceUnion)
    .replace('{{FALLBACKS_BODY}}', tsLiteral(fallbacks))
}

function renderRouteClient() {
  const header = '// GENERATED by packages/scripts/gen-client-seam.mjs from packages/scripts/templates/client/route-client.ts.tmpl — do not edit.'
  return readFileSync(join(templates, 'route-client.ts.tmpl'), 'utf8').replace('{{HEADER}}', header)
}

const hostRoutes = await loadHostRoutes()
const loadedFallbacks = await loadCommandFallbacks()
const outputs = []
const routesText = renderRoutes(hostRoutes)
const clientText = renderRouteClient()
const diagnosticKeys = await loadDiagnosticKeys()
const contractsText = renderContracts(diagnosticKeys)
const statesText = renderStates()
const surfaces = Object.keys(SURFACE_IDS).filter((key) => hostRoutes[key] !== undefined)
const surfaceUnion = surfaces.map((key) => "'" + SURFACE_IDS[key] + "'").join(' | ')
const fallbacks = {}
for (const surface of surfaces) {
  const id = SURFACE_IDS[surface]
  const entry = loadedFallbacks.table[id]
  if (entry === undefined) {
    console.error('gen-client-seam: COMMAND_FALLBACKS has no entry for surface ' + id)
    process.exit(2)
  }
  fallbacks[id] = entry
}
const fallbacksText = renderFallbacks(surfaceUnion, fallbacks)
for (const pkg of PACKAGES) {
  const dir = join(root, pkg, 'src', 'client')
  if (!existsSync(dir)) {
    console.error('gen-client-seam: client directory is missing: ' + dir)
    process.exit(2)
  }
  outputs.push({ path: join(dir, 'routes.generated.ts'), content: routesText })
  outputs.push({ path: join(dir, 'route-client.generated.ts'), content: clientText })
  outputs.push({ path: join(dir, 'contracts.generated.ts'), content: contractsText })
  outputs.push({ path: join(dir, 'fallbacks.generated.ts'), content: fallbacksText })
  outputs.push({ path: join(dir, 'states.generated.ts'), content: statesText })
}

const drifts = []
for (const output of outputs) {
  const current = existsSync(output.path) ? readFileSync(output.path, 'utf8') : undefined
  if (current === output.content) continue
  drifts.push(output.path)
  if (!CHECK) writeFileSync(output.path, output.content, 'utf8')
}
if (CHECK && drifts.length > 0) {
  if (JSON_OUT) console.log(JSON.stringify({ ok: false, drifted: drifts }, null, 2))
  else {
    console.error('gen-client-seam --check: ' + drifts.length + ' generated client file(s) are stale:')
    for (const drift of drifts) console.error('  - ' + drift)
  }
  process.exit(1)
}
if (JSON_OUT) console.log(JSON.stringify({ ok: true, check: CHECK, wrote: CHECK ? [] : drifts, endpoints: Object.values(hostRoutes).reduce((sum, surface) => sum + Object.keys(surface).length, 0) }, null, 2))
else console.log('gen-client-seam: ' + (CHECK ? 'OK — ' + String(outputs.length) + ' generated client file(s) in sync' : 'wrote ' + String(drifts.length) + ' generated client file(s)'))
