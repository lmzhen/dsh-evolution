/**
 * Generate the family-facing ports that can be derived from platform service
 * types. The manual contract files still own the family-only shapes; this file
 * is the single place where a port is a `Pick` of the authoritative platform
 * service instead of a hand-copied signature list.
 *
 * Usage: node packages/scripts/gen-contract-ports.mjs [--check]
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const evolution = resolve(here, '..')
const source = resolve(here, 'contract-ports.json')
const target = resolve(evolution, 'evolution-platform/src/contract/ports.generated.ts')
const check = process.argv.includes('--check')

const config = JSON.parse(await readFile(source, 'utf8'))
const ports = config.ports ?? []
const byModule = new Map()
for (const port of ports) {
  const names = byModule.get(port.module) ?? []
  names.push(port.service)
  byModule.set(port.module, [...new Set(names)].sort())
}
const imports = [...byModule.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([module, names]) => `import type { ${names.join(', ')} } from '${module}'`)
const declarations = ports.map((port) => {
  const members = port.members.map((member) => `'${member}'`).join(' | ')
  const base = port.partial === true ? `Partial<Pick<${port.service}, ${members}>>` : `Pick<${port.service}, ${members}>`
  return `export type ${port.name} = ${base}${port.extra ?? ''}`
})
const output = [
  '/**',
  ' * GENERATED by packages/scripts/gen-contract-ports.mjs — do not edit.',
  ' * Source: packages/scripts/contract-ports.json',
  ' */',
  ...imports,
  '',
  ...declarations.flatMap((line) => [line, '']),
].join('\n')

if (check) {
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current !== output) {
    console.error('gen-contract-ports: generated ports are stale; run node packages/scripts/gen-contract-ports.mjs')
    process.exit(1)
  }
  console.log(`gen-contract-ports: up to date (${ports.length} ports)`)
} else {
  await writeFile(target, output)
  console.log(`gen-contract-ports: wrote ${target} (${ports.length} ports)`)
}
