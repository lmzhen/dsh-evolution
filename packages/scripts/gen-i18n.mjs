#!/usr/bin/env node
/**
 * Generate the family client dictionaries from the single i18n catalog.
 *
 * Catalog files live under packages/scripts/i18n/catalog. Each file declares one
 * client namespace and one object per message: { zh, en, ja, es, fr, de, ru, pt }.
 * Missing locales are filled from English while B6 is being translated; --strict
 * rejects them, and CI uses --strict once all columns are complete.
 */
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..', '..')
const CATALOG = join(ROOT, 'packages/scripts/i18n/catalog')
const TARGET = join(ROOT, 'packages/evolution-client-kit/src/generated/i18n.generated.ts')
export const SUPPORTED_LOCALES = ['zh', 'en', 'ja', 'es', 'fr', 'de', 'ru', 'pt']

const args = new Set(process.argv.slice(2))
const CHECK = args.has('--check')
const STRICT = args.has('--strict')

function loadCatalog(value) {
  if (typeof value !== 'object' || value === null) throw new Error('catalog root must be an object')
  const namespace = value.namespace
  if (typeof namespace !== 'string' || namespace.length === 0) throw new Error('catalog namespace is required')
  const messages = value.messages
  if (typeof messages !== 'object' || messages === null) throw new Error(namespace + ': messages must be an object')
  const keys = Object.keys(messages)
  if (keys.length === 0) throw new Error(namespace + ': no messages')
  const missing = []
  const dictionaries = Object.fromEntries(SUPPORTED_LOCALES.map(locale => [locale, {}]))
  for (const key of keys) {
    const row = messages[key]
    if (typeof row !== 'object' || row === null) throw new Error(namespace + '.' + key + ': row must be an object')
    const en = row.en
    if (typeof en !== 'string' || en.length === 0) throw new Error(namespace + '.' + key + ': en is required')
    for (const locale of SUPPORTED_LOCALES) {
      const text = typeof row[locale] === 'string' && row[locale].length > 0 ? row[locale] : en
      if (typeof row[locale] !== 'string' || row[locale].length === 0) missing.push(namespace + '.' + key + ':' + locale)
      dictionaries[locale][key] = text
    }
    const slots = [...en.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort()
    for (const locale of SUPPORTED_LOCALES) {
      const text = dictionaries[locale][key]
      const other = [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort()
      if (other.join('|') !== slots.join('|')) throw new Error(namespace + '.' + key + ':' + locale + ': slot mismatch')
    }
  }
  if (STRICT && missing.length > 0) throw new Error(namespace + ': missing translations: ' + missing.slice(0, 8).join(', ') + (missing.length > 8 ? ' …' : ''))
  return { namespace, dictionaries, count: keys.length, missing }
}

function render(catalogs) {
  const lines = [
    '/**',
    ' * GENERATED by packages/scripts/gen-i18n.mjs — do not edit.',
    ' * The source of truth is packages/scripts/i18n/catalog/*.json.',
    ' */',
    '',
    'export const SUPPORTED_LOCALES = ' + JSON.stringify(SUPPORTED_LOCALES) + ' as const',
    'export type SupportedLocale = typeof SUPPORTED_LOCALES[number]',
    '',
    'export const DICTIONARIES = {',
  ]
  for (const catalog of catalogs) {
    lines.push('  ' + JSON.stringify(catalog.namespace) + ': {')
    for (const locale of SUPPORTED_LOCALES) {
      lines.push('    ' + locale + ': ' + JSON.stringify(catalog.dictionaries[locale], null, 2).replace(/\n/g, '\n    ') + ',')
    }
    lines.push('  },')
  }
  lines.push('} as const')
  lines.push('')
  lines.push('export type FamilyNamespace = keyof typeof DICTIONARIES')
  lines.push('export type MessageKeyOf<N extends FamilyNamespace> = keyof (typeof DICTIONARIES)[N][\'en\']')
  lines.push('')
  lines.push('export function dictionariesFor<N extends FamilyNamespace>(namespace: N): (typeof DICTIONARIES)[N] {')
  lines.push('  return DICTIONARIES[namespace]')
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

const files = (await readdir(CATALOG)).filter(name => name.startsWith('ui.') && name.endsWith('.json')).sort()
if (files.length === 0) throw new Error('no ui.*.json catalogs under ' + CATALOG)
const catalogs = []
for (const file of files) {
  const value = JSON.parse(await readFile(join(CATALOG, file), 'utf8'))
  const catalog = loadCatalog(value)
  catalogs.push(catalog)
  if (catalog.missing.length > 0) console.warn('gen-i18n: ' + catalog.namespace + ': ' + String(catalog.missing.length) + ' value(s) fall back to English')
}
const output = render(catalogs) + '\n'
const current = await readFile(TARGET, 'utf8').catch(() => '')
if (CHECK) {
  if (current !== output) {
    console.error('gen-i18n: generated dictionary is stale; run node packages/scripts/gen-i18n.mjs')
    process.exit(1)
  }
  console.log('gen-i18n: OK — ' + String(catalogs.length) + ' namespace(s), ' + String(catalogs.reduce((sum, c) => sum + c.count, 0)) + ' key(s)')
} else {
  await writeFile(TARGET, output)
  console.log('gen-i18n: wrote ' + TARGET + ' (' + String(catalogs.length) + ' namespace(s))')
}
