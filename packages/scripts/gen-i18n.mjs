#!/usr/bin/env node
/**
 * Generate one client dictionary module per namespace, plus the aggregate index.
 *
 * Per-namespace files let each panel bundle import only its own copy; the aggregate
 * exists for callers that need the full map (tests, tooling) and is type-only from
 * the runtime surfaces.
 */
import { mkdir, readFile, writeFile, readdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'

const SCRIPTS = import.meta.dirname
const EVOLUTION_ROOT = resolve(SCRIPTS, '..')
const CATALOG = join(SCRIPTS, 'i18n/catalog')
const GENERATED = join(EVOLUTION_ROOT, 'evolution-client-kit/src/generated')
const PER_NAMESPACE = join(GENERATED, 'i18n')
const TARGET = join(GENERATED, 'i18n.generated.ts')
export const SUPPORTED_LOCALES = ['zh', 'en', 'ja', 'es', 'fr', 'de', 'ru', 'pt']

const args = new Set(process.argv.slice(2))
const CHECK = args.has('--check')
const STRICT = args.has('--strict')

function loadCatalog(value) {
  if (typeof value !== 'object' || value === null) throw new Error('catalog root must be an object')
  const namespace = value.namespace
  if (typeof namespace !== 'string' || namespace.length === 0) throw new Error('catalog namespace is required')
  const messages = value.messages
  if (typeof messages !== 'object' || messages === null) throw new Error(namespace + ': messages must be an object')
  const keys = Object.keys(messages)
  if (keys.length === 0) throw new Error(namespace + ': no messages')
  const missing = []
  const dictionaries = Object.fromEntries(SUPPORTED_LOCALES.map(locale => [locale, {}]))
  for (const key of keys) {
    const row = messages[key]
    if (typeof row !== 'object' || row === null) throw new Error(namespace + '.' + key + ': row must be an object')
    const en = row.en
    if (typeof en !== 'string' || en.length === 0) throw new Error(namespace + '.' + key + ': en is required')
    for (const locale of SUPPORTED_LOCALES) {
      const text = typeof row[locale] === 'string' && row[locale].length > 0 ? row[locale] : en
      if (typeof row[locale] !== 'string' || row[locale].length === 0) missing.push(namespace + '.' + key + ':' + locale)
      dictionaries[locale][key] = text
    }
    const slots = [...en.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort()
    for (const locale of SUPPORTED_LOCALES) {
      const text = dictionaries[locale][key]
      const other = [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort()
      if (other.join('|') !== slots.join('|')) throw new Error(namespace + '.' + key + ':' + locale + ': slot mismatch')
    }
  }
  if (STRICT && missing.length > 0) throw new Error(namespace + ': missing translations: ' + missing.slice(0, 8).join(', ') + (missing.length > 8 ? ' …' : ''))
  return { namespace, dictionaries, count: keys.length, missing }
}

const header = (namespace) => [
  '/**',
  ' * GENERATED by packages/scripts/gen-i18n.mjs — do not edit.',
  ' * Source: packages/scripts/i18n/catalog for ' + namespace + '.',
  ' */',
  '',
]

function renderNamespace(catalog) {
  const body = []
  body.push('export const dictionaries = {')
  for (const locale of SUPPORTED_LOCALES) {
    body.push('  ' + locale + ': ' + JSON.stringify(catalog.dictionaries[locale], null, 2).replace(/\n/g, '\n  ') + ',')
  }
  body.push('} as const')
  body.push('')
  return header(catalog.namespace).concat(body).join('\n') + '\n'
}

const identifier = (namespace) => namespace.replace(/[^A-Za-z0-9]+(.)/g, (_m, c) => c.toUpperCase()).replace(/^[^A-Za-z]+/, '')

function renderAggregate(catalogs) {
  const lines = [
    '/**',
    ' * GENERATED by packages/scripts/gen-i18n.mjs — do not edit.',
    ' * Source of truth: packages/scripts/i18n/catalog/*.json.',
    ' */',
    '',
  ]
  for (const catalog of catalogs) lines.push('import { dictionaries as ' + identifier(catalog.namespace) + ' } from ' + JSON.stringify('./i18n/' + catalog.namespace + '.ts') + '')
  lines.push('')
  lines.push('export const SUPPORTED_LOCALES = ' + JSON.stringify(SUPPORTED_LOCALES) + ' as const')
  lines.push('export type SupportedLocale = typeof SUPPORTED_LOCALES[number]')
  lines.push('')
  lines.push('export const DICTIONARIES = {')
  for (const catalog of catalogs) lines.push('  ' + JSON.stringify(catalog.namespace) + ': ' + identifier(catalog.namespace) + ',')
  lines.push('} as const')
  lines.push('')
  lines.push('export type FamilyNamespace = keyof typeof DICTIONARIES')
  lines.push("export type MessageKeyOf<N extends FamilyNamespace> = keyof (typeof DICTIONARIES)[N]['en']")
  lines.push('')
  lines.push('export function dictionariesFor<N extends FamilyNamespace>(namespace: N): (typeof DICTIONARIES)[N] {')
  lines.push('  return DICTIONARIES[namespace]')
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

const files = (await readdir(CATALOG)).filter(name => name.startsWith('ui.') && name.endsWith('.json')).sort()
if (files.length === 0) throw new Error('no ui.*.json catalogs under ' + CATALOG)
const catalogs = []
for (const file of files) {
  const value = JSON.parse(await readFile(join(CATALOG, file), 'utf8'))
  const catalog = loadCatalog(value)
  catalogs.push(catalog)
  if (catalog.missing.length > 0) console.warn('gen-i18n: ' + catalog.namespace + ': ' + String(catalog.missing.length) + ' value(s) fall back to English')
}

const outputs = new Map()
for (const catalog of catalogs) outputs.set(join(PER_NAMESPACE, catalog.namespace + '.ts'), renderNamespace(catalog))
outputs.set(TARGET, renderAggregate(catalogs) + '\n')

let stale = false
for (const [path, output] of outputs) {
  const current = await readFile(path, 'utf8').catch(() => '')
  if (current !== output) {
    stale = true
  }
}
if (CHECK) {
  if (stale) {
    console.error('gen-i18n: generated dictionaries are stale; run node packages/scripts/gen-i18n.mjs')
    process.exit(1)
  }
  console.log('gen-i18n: OK — ' + String(catalogs.length) + ' namespace(s), ' + String(catalogs.reduce((sum, c) => sum + c.count, 0)) + ' key(s)')
} else {
  if (stale) {
    await mkdir(PER_NAMESPACE, { recursive: true })
    for (const [path, output] of outputs) await writeFile(path, output)
    console.log('gen-i18n: wrote ' + String(catalogs.length) + ' namespace file(s) + aggregate')
  } else {
    console.log('gen-i18n: up to date')
  }
}
