#!/usr/bin/env node
/** Generate the client-facing product surface from surface-catalog.json. */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = process.argv[2] ?? process.cwd()
const here = dirname(fileURLToPath(import.meta.url))
const check = process.argv.includes('--check')
const catalog = JSON.parse(readFileSync(join(here, 'surface-catalog.json'), 'utf8'))
const target = join(root, 'evolution-ui', 'src', 'panels', 'settings', 'generated-surface.ts')
const rows = (catalog.rowConfigs ?? []).map((row) => ({
  rowId: row.rowId,
  namespaces: row.namespaces,
  bundles: row.bundles,
  order: row.order,
}))
const body = `/** GENERATED by packages/scripts/gen-surface-catalog.mjs — do not edit. */
export interface RowConfigSurface {
  readonly rowId: string
  readonly namespaces: readonly string[]
  readonly bundles: readonly string[]
  readonly order: number
}

export const PRODUCT_BUNDLE = '${catalog.installBundles[0]}'
export const ROW_CONFIG_SURFACES: readonly RowConfigSurface[] = ${JSON.stringify(rows, null, 2)}
`
if (check) {
  if (!existsSync(target)) { console.error('gen-surface-catalog: missing ' + target); process.exit(1) }
  if (readFileSync(target, 'utf8') !== body) { console.error('gen-surface-catalog: ' + target + ' is stale (rerun without --check)'); process.exit(1) }
  console.log('gen-surface-catalog: up to date — ' + rows.length + ' row config(s)')
} else {
  writeFileSync(target, body, 'utf8')
  console.log('gen-surface-catalog: wrote ' + target + ' (' + rows.length + ' row config(s))')
}
