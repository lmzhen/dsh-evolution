#!/usr/bin/env node
/**
 * Generate the family's VERSION AND PURPOSE into the settings client half (G5.10 / U-10).
 *
 * U-10 asks the settings surface to show a one-line summary a reader can judge by: which family
 * version am I looking at, and what is this surface for. Both values are known at BUILD time, and the
 * browser half cannot read them itself — `build-client.mjs` keeps every `@deepseek-ai/*` specifier
 * external, and reading `package.json` from the browser is not a thing that exists. So the pair is
 * GENERATED here from the two files that own the values (the repository `package.json` for the
 * version, the settings-ui `package.json` for the purpose) and the client half carries a constant.
 *
 * The same version fact is checked for the DOCUMENTS by `family-facts.json` (kind
 * `family-version`, G4.4): one value, two consumers, no hand-written copy.
 *
 * Usage: node gen-about.mjs <evolution-root> [--check]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))

/** Where the generated copy lives inside the package. */
const RELATIVE = 'evolution-settings-ui/src/client/generated-about.ts'

/**
 * Find the repository root that owns `package.json`: the mirror layout keeps it two levels above
 * `packages/scripts`, a build overlay one level above `packages/evolution/scripts`.
 * @returns the directory, or null when the tree does not carry one.
 */
function repoRoot() {
  for (const candidate of [join(HERE, '..', '..'), join(HERE, '..'), join(HERE, '..', '..', '..')]) {
    const file = join(candidate, 'package.json')
    if (!existsSync(file)) continue
    // The FAMILY root, not whatever repository happens to sit above the overlay: a CI build inside the
    // platform's repository finds `@deepseek-ai/dsh-root` three levels up, whose version is the
    // PLATFORM's. Matching the family name keeps that from being written into a family constant.
    try {
      if (JSON.parse(readFileSync(file, 'utf8')).name === 'dsh-evolution') return candidate
    } catch { /* an unreadable root is not the family's */ }
  }
  return null
}

/**
 * One single-quoted TypeScript string literal, escaped for the two characters a version or a
 * description may carry.
 * @param value - the literal text.
 * @returns the literal.
 */
function single(value) {
  return ["'", String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'"), "'"].join('')
}

/**
 * Render the generated module.
 * @param root - the packages root the guard was pointed at.
 * @returns the file body.
 */
export function renderAbout(root) {
  const repo = repoRoot()
  // A build overlay that mirrors only packages/evolution carries no repository root. Say so and skip —
  // the mirror's own loss of the file is caught by verify-gate-manifest, exactly like the platform
  // version fact (lib-doc-facts.mjs). Throwing here would redden every overlay build forever.
  if (repo === null) return null
  const version = JSON.parse(readFileSync(join(repo, 'package.json'), 'utf8')).version
  const pkg = JSON.parse(readFileSync(join(resolve(root), 'evolution-settings-ui', 'package.json'), 'utf8'))
  const purpose = String(pkg.description ?? '')
  return [
    '/**',
    ' * GENERATED by packages/scripts/gen-about.mjs — do not edit.',
    ' *',
    ' * The version comes from the repository package.json and the purpose from this package own',
    ' * description, so the settings surface can state both without a hand-written copy.',
    ' */',
    '',
    '/** The family version this surface belongs to. */',
    'export const FAMILY_VERSION = ' + single(version),
    '',
    '/** What this surface is for, in one line. */',
    'export const PACKAGE_PURPOSE = ' + single(purpose),
    '',
  ].join(String.fromCharCode(10))
}

const argv = process.argv.slice(2)
const check = argv.includes('--check')
const root = resolve(argv.find((arg) => !arg.startsWith('--')) ?? 'packages')
const target = join(root, RELATIVE)
const rendered = renderAbout(root)
if (rendered === null) {
  console.log('gen-about: not armed in this layout — no repository package.json above ' + HERE)
  process.exit(0)
}
if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : ''
  if (current !== rendered) {
    console.error('gen-about: ' + target + ' is STALE (rerun without --check)')
    process.exit(1)
  }
  console.log('gen-about: OK — the client summary matches the repository version and the package description')
  process.exit(0)
}
writeFileSync(target, rendered)
console.log('gen-about: wrote ' + target)
