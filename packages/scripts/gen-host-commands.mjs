#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
const SCRIPTS = import.meta.dirname
const EVOLUTION_ROOT = resolve(SCRIPTS, '..')
const SOURCE = resolve(SCRIPTS, 'i18n/catalog/host.commands.json')
const TARGET = resolve(EVOLUTION_ROOT, 'evolution-commands/src/generated/host-commands.ts')
const LOCALES = ['zh', 'en', 'ja', 'es', 'fr', 'de', 'ru', 'pt']
const CHECK = process.argv.includes('--check')
const STRICT = process.argv.includes('--strict')
const source = JSON.parse(await readFile(SOURCE, 'utf8'))
const rows = {}
const missing = []
for (const [id, row] of Object.entries(source.messages ?? {})) {
  const base = typeof row.en === 'string' && row.en.length > 0 ? row.en : row.zh
  if (typeof base !== 'string' || base.length === 0) throw new Error(id + ': text required')
  const out = {}
  for (const locale of LOCALES) {
    if (typeof row[locale] === 'string' && row[locale].length > 0) out[locale] = row[locale]
    else { out[locale] = base; missing.push(id + ':' + locale) }
  }
  rows[id] = out
}
if (STRICT && missing.length > 0) throw new Error('missing translations: ' + missing.slice(0, 8).join(', '))
const output = ['/**', ' * GENERATED by packages/scripts/gen-host-commands.mjs — do not edit.', ' */', '', 'export const HOST_COMMANDS = ' + JSON.stringify(rows, null, 2).replace(/\n/g, '\n  ') + ' as const', '', 'export type HostCommandKey = keyof typeof HOST_COMMANDS', ''].join('\n') + '\n'
const current = await readFile(TARGET, 'utf8').catch(() => '')
if (CHECK) { if (current !== output) { console.error('gen-host-commands: generated table is stale'); process.exit(1) } console.log('gen-host-commands: OK — ' + String(Object.keys(rows).length) + ' key(s)') }
else { await mkdir(dirname(TARGET), { recursive: true }); await writeFile(TARGET, output); console.log('gen-host-commands: wrote ' + TARGET) }
