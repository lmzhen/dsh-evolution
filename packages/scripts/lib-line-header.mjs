#!/usr/bin/env node
/**
 * lib-line-header — the ONE place that turns a line manifest into the conclusion header
 * (contract C1, G1.5).
 *
 * Why: every conclusion the family prints ("the suite is green", "the guards are clean") is only
 * meaningful together with the LINE it was measured on. Two of the bed's sources are machine state,
 * so a report without a line is an unfalsifiable claim — the plan's rule is: a green result may not be
 * claimed when the line is unknown.
 *
 * Shape: `line: pin=<sha> bed=<path> lineId=<12 hex> entries=<n>`
 *   lineId = sha256 of the sorted `<id>	<kind>` list — same bed ⇒ same id, any resolution change ⇒
 *   a different id (so two reports can be compared without eyeballing 358 paths).
 *
 * usage: node lib-line-header.mjs [--manifest <path>] [--print] [--json]
 *        (also importable: readLineHeader(manifestPath) → { pin, bed, lineId, entries })
 */
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
/** Where the machine that owns the bed writes its manifest (generated by _tools/line-manifest.mjs). */
/** The bed manifest that belongs to THIS repo. It used to point at `_lab/line-manifest.json`, a
 * machine-local scratch copy carrying 368 host-absolute paths and the same file NAME as this one -
 * two artifacts, one name, and the default reader pointed at the wrong one (review 2026-10-15). */
export const DEFAULT_MANIFEST = resolve(process.env.FAMILY_LINE_MANIFEST ?? join(here, 'files', 'line-manifest.json'))

/** @returns the header, or null when there is no manifest (the caller decides how loud that is). */
export function readLineHeader(manifestPath = DEFAULT_MANIFEST) {
  if (!existsSync(manifestPath)) return null
  let manifest
  try { manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) } catch { return null }
  const entries = Array.isArray(manifest.entries) ? manifest.entries : []
  if (entries.length === 0) return null
  const identity = entries.map((entry) => String(entry.id) + '\t' + String(entry.kind)).sort().join('\n')
  const lineId = createHash('sha256').update(identity).digest('hex').slice(0, 12)
  return { pin: manifest.pin ?? 'unknown', bed: manifest.bed?.mono ?? 'unknown', lineId, entries: entries.length }
}

/** @returns the one-line conclusion header. */
export function formatLineHeader(header) {
  return header === null
    ? 'line: UNKNOWN — no line manifest here; a green result must NOT be claimed from this run'
    : 'line: pin=' + header.pin + ' bed=' + header.bed + ' lineId=' + header.lineId + ' entries=' + header.entries
}

/**
 * The CI form: there is no bed manifest on a CI runner, but the line is still fully determined —
 * the checkout (`pin`) plus the declared kind policy (`lineId` = hash of the policy file). This is
 * deliberately separate from the local form so the local rule stays fail-closed on a missing manifest.
 * @param {string} policyPath
 * @returns {string}
 */
export function formatCiLineHeader(policyPath) {
  let pin = 'unknown'
  try { pin = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim() } catch { pin = 'unknown' }
  let policyHash = 'unknown'
  try { policyHash = createHash('sha256').update(readFileSync(policyPath, 'utf8')).digest('hex').slice(0, 12) } catch { policyHash = 'unknown' }
  return 'line: pin=' + pin + ' bed=ci lineId=policy:' + policyHash
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
if (isMain) {
  const argv = process.argv.slice(2)
  const at = argv.indexOf('--manifest')
  if (argv.includes('--ci')) {
    const policyAt = argv.indexOf('--policy')
    const policyPath = policyAt >= 0 && argv[policyAt + 1] !== undefined ? argv[policyAt + 1] : join(here, 'line-policy.json')
    console.log(formatCiLineHeader(policyPath))
    process.exitCode = 0
  } else {
    const header = readLineHeader(at >= 0 && argv[at + 1] !== undefined ? argv[at + 1] : DEFAULT_MANIFEST)
    if (argv.includes('--json')) console.log(JSON.stringify(header))
    else console.log(formatLineHeader(header))
    process.exitCode = header === null ? 1 : 0
  }
}
